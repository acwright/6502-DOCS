function kernalJumpTable() {
  const kernal = facts('kernal.json')
  const version = kernal.$meta.biosVersion
  const bySlot = Object.fromEntries(kernal.slots.map((s) => [s.name, s]))

  // Grouped the way a programmer arrives at them, which is not the order the
  // table is laid out in — the same grouping docs/assembly/kernal.md uses.
  const GROUPS = [
    ['Console', ['Chrout', 'Chrin', 'PrintStr', 'PrintCRLF', 'PrintDecU16', 'WriteBuffer', 'ReadBuffer', 'BufferSize', 'SetIOMode', 'GetIOMode']],
    ['The screen', ['InitVideo', 'VideoClear', 'VideoPutChar', 'VideoChroutRaw', 'VideoSetCursor', 'VideoGetCursor', 'VideoScroll', 'VideoSetColor']],
    ['Sound', ['InitSID', 'Beep', 'SidPlayNote', 'SidSilence', 'SidSetVolume']],
    ['Keyboard and sticks', ['InitKB', 'ReadJoystick1', 'ReadJoystick2', 'KBDisable', 'KBEnable']],
    ['Files', ['FsLoadFileAddr', 'FsSaveFileAddr', 'FsLoadFile', 'FsSaveFile', 'FsDeleteFile', 'FsFormatDisk', 'FsSetDisk', 'FsGetDisk', 'FsPrintDisk']],
    ['The card itself', ['StReadSector', 'StWriteSector', 'StWaitReady']],
    ['Serial', ['InitSC', 'SerialChrout', 'XModemLoad', 'XModemSave']],
    ['Clock and lasting memory', ['RtcReadTime', 'RtcReadDate', 'RtcWriteTime', 'RtcWriteDate', 'RtcReadNVRAM', 'RtcWriteNVRAM']],
    ['The machine', ['SysDelay', 'KernalInit', 'KernalVersion']]
  ]

  const listed = new Set(GROUPS.flatMap(([, names]) => names))
  const missing = kernal.slots.filter((s) => !listed.has(s.name))
  if (missing.length) {
    throw new Error(`kernal-jump-table: ${missing.length} slot(s) ungrouped: ${missing.map((s) => s.name).join(', ')}`)
  }

  const group = (title, names) =>
    section(title,
      table([{ label: 'Addr', width: '13%' }, { label: 'Name', width: '28%' }, { label: 'In / out' }],
        names.map((n) => {
          const s = bySlot[n]
          if (!s) throw new Error(`kernal-jump-table: no slot named ${n}`)
          const io = [
            s.input?.length ? `<strong>in</strong> ${esc(s.input.join('; '))}` : '',
            s.output?.length ? `<strong>out</strong> ${esc(s.output.join('; '))}` : ''
          ].filter(Boolean).join(' &middot; ')
          return [addr(esc(s.address)), label(esc(s.name)), desc(`${rich(s.summary)}${io ? `<br>${io}` : ''}`)]
        })))

  const half = (from, to) => GROUPS.slice(from, to).map(([t, n]) => group(t, n))

  return card({
    file: 'kernal-jump-table.html',
    title: '6502 Kernal — Jump Table',
    side: SIDE(`Kernal &middot; BIOS v${version}`),
    subtitle: '6502 KERNAL — JUMP TABLE',
    style: '--w-addr: 13%; --w-label: 28%',
    pages: [
      {
        heading: 'Kernal Jump Table',
        sections: [
          section('The contract',
            note('Call the slot, never the implementation.',
              `${kernal.publishedSlots} entry points, three bytes each, starting at ` +
              `<code>${esc(kernal.base)}</code> and in an order that does not change. ` +
              `<code>jsr ${esc(kernal.base)}</code> prints a character on this ROM and on the next one. ` +
              `<code>6502.inc</code> gives every slot its name, so you will write <code>jsr Chrout</code>.`),
            note('Arguments go in registers.',
              'A, X and Y in, A, X, Y or the carry flag out. Nothing is passed on the stack.'),
            note('The tail of the table.',
              `${kernal.reserved.count} slots from <code>${esc(kernal.reserved.start)}</code> to ` +
              `<code>${esc(kernal.reserved.end)}</code> are reserved. Each is a real jump to a bare ` +
              '<code>RTS</code>, so calling one is harmless now and may do something later. Do not put ' +
              'your own code there.')),
          ...half(0, 4)
        ]
      },
      { heading: 'Kernal Jump Table', sections: half(4, 9) }
    ]
  })
}

