/** HTML-escape, then let a few typographic niceties through as entities. */
function esc(text) {
  return String(text ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

/**
 * Render the Markdown-ish spans the fact base carries in its prose fields. The
 * BIOS source writes its comments that way and the JSON keeps them verbatim,
 * so the cards have to understand the same things the chapters do: `code`, and
 * **bold**, which JOY's summary uses and which the card used to print with its
 * asterisks still attached.
 */
function rich(text) {
  return esc(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
}

/** Two columns is the house default; a page asks for another count by name. */
const COLUMN_CLASS = { 1: ' one-col', 2: '', 3: ' three-col' }

function card({ file, title, side, subtitle, bodyClass = '', style = '', pages }) {
  const head = [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="UTF-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
    `<title>${esc(title)}</title>`,
    '<link rel="stylesheet" href="card.css">',
    '</head>',
    `<body class="card${bodyClass ? ' ' + bodyClass : ''}"${style ? ` style="${style}"` : ''}>`,
    '',
    '<!-- Generated by scripts/build-cards.mjs from data/*.json — do not edit by hand. -->',
    '',
    '<div class="print-hint">To print: letter &middot; 100% scale &middot; margins off &middot; background graphics ON</div>'
  ]

  const body = pages.map((page, i) => {
    const label =
      pages.length <= 2 ? (i === 0 ? 'FRONT' : 'BACK') : `${i + 1} / ${pages.length}`
    return [
      '',
      `<!-- ═══════════════════════════════════════════════════ PAGE ${i + 1} -->`,
      '<div class="page">',
      '',
      '  <div class="pg-header">',
      `    <h1>${esc(page.heading ?? title)}</h1>`,
      `    <div class="side-info">${side}</div>`,
      '  </div>',
      '',
      `  <div class="pg-body${COLUMN_CLASS[page.cols ?? 2]}">`,
      indent(page.sections.join('\n'), 4),
      '  </div><!-- /pg-body -->',
      '',
      '  <div class="pg-footer">',
      `    <span>${esc(subtitle)}</span>`,
      '    <span>A.C. WRIGHT 6502</span>',
      `    <span class="pg-num">${label}</span>`,
      '  </div>',
      '',
      '</div><!-- /page -->'
    ].join('\n')
  })

  return {
    file,
    content: [...head, ...body, '', '</body>', '</html>', ''].join('\n')
  }
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.trim() ? pad + line : line))
    .join('\n')
}

function section(title, ...blocks) {
  return sectionWith('section', title, ...blocks)
}

/**
 * A section that runs on across a column break instead of being kept whole.
 *
 * The default is to keep a section together, which is right for a short table
 * with a note under it. It is wrong for a long list: a 64-row table cannot fit
 * in one column whatever the browser does, so `break-inside: avoid` first
 * pushes the whole thing to the next column — stranding whatever was left of
 * the one before it — and only then breaks it anyway. Two of those on a page
 * is how the character set ended up running off the right-hand edge.
 */
function flowSection(title, ...blocks) {
  return sectionWith('section flow', title, ...blocks)
}

function sectionWith(cls, title, ...blocks) {
  return [
    `<div class="${cls}">`,
    `  <span class="sec-title">${esc(title)}</span>`,
    indent(blocks.filter(Boolean).join('\n'), 2),
    '</div>'
  ].join('\n')
}

function table(headers, rows) {
  const head = headers.length
    ? `  <thead><tr>${headers.map((h) => `<th${h.width ? ` style="width:${h.width}"` : ''}>${esc(h.label)}</th>`).join('')}</tr></thead>`
    : ''
  const body = rows
    .map((cells) => `    <tr>${cells.map((c) => `<td class="${c.cls ?? 'td-desc'}"${c.span ? ` colspan="${c.span}"` : ''}>${c.html}</td>`).join('')}</tr>`)
    .join('\n')
  return ['<table>', head, '  <tbody>', body, '  </tbody>', '</table>'].filter(Boolean).join('\n')
}

function note(strong, text) {
  return `<div class="note-box">${strong ? `<strong>${esc(strong)}</strong> ` : ''}${text}</div>`
}

const cmd = (html) => ({ cls: 'td-cmd', html })
const syn = (html) => ({ cls: 'td-syn', html })
const addr = (html) => ({ cls: 'td-addr', html })
const label = (html) => ({ cls: 'td-label', html })
const desc = (html) => ({ cls: 'td-desc', html })

const SIDE = (line) => `A.C. Wright 6502 BIOS<br>${line}`

/**
 * Lowercase a sentence's first word so it can be joined into a list — unless
 * that word is an acronym, which stays as it was written. "The BRK statement"
 * wants to become "the BRK statement"; "ESC at the boot splash" does not want
 * to become "eSC at the boot splash", which is what the card used to print.
 */
function lowerFirst(text) {
  const first = text.split(' ', 1)[0]
  if (first === first.toUpperCase() && /[A-Z]/.test(first)) return text
  return text.charAt(0).toLowerCase() + text.slice(1)
}

