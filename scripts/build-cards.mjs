function main() {
  const check = process.argv.includes('--check')
  const built = [
    basicReference(),
    monitorReference(),
    kernalJumpTable(),
    memoryMap(),
    characterMap(),
    keyboardLayout(),
    f18aRegisters()
  ]

  let stale = 0
  for (const { file, content } of built) {
    const path = join(CARDS, file)
    if (check) {
      const current = existsSync(path) ? readFileSync(path, 'utf-8') : ''
      if (current !== content) {
        console.error(`FAIL cards/${file} is out of date`)
        stale++
      } else {
        console.log(`ok   cards/${file}`)
      }
      continue
    }
    writeFileSync(path, content)
    console.log(`wrote cards/${file}  (${content.split('\n').length} lines)`)
  }

  if (check && stale) {
    console.error(`\n${stale} card(s) stale — run: npm run cards`)
    process.exit(1)
  }
  if (check) console.log('\nevery generated card is current with the fact base')
}

main()
