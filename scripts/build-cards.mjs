#!/usr/bin/env node
/**
 * build-cards.mjs — write the reference cards that come out of the fact base.
 *
 *   npm run cards            # write them
 *   npm run cards:verify     # fail if any is out of date (CI)
 *
 * Six of the cards in `docs/public/cards/` are nothing but repo data in a
 * letter-page layout: the BASIC and Monitor references, the Kernal jump table,
 * the memory map and the character set come from `data/*.json`, and the
 * keyboard layout from the KLE file in `assets/keyboard/`. Hand-maintaining
 * those is how the originals ended up documenting a v1.0 machine on a v1.5 ROM
 * — so they are generated here, from the same files the chapters render, and
 * CI fails if the checked-in copy has drifted.
 *
 * The other eight — the ACE, COB, DEV, VCS and KIM sheets, the connector
 * pinouts, the keyboard matrix and the keypad map — are hand-written, because
 * their content comes from boards and firmware rather than from the ROM. Each
 * cites its source in a comment at the top of the file, and
 * `scripts/check-cards.mjs` polices every card in the directory equally,
 * generated, hand-written and archived alike.
 */

