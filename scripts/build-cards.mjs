/*
 * A note on the section titles below: `section()` escapes what it is given, so
 * a title has to carry the dash as a character rather than as `&ndash;`. It
 * used to be written as the entity, and the card printed a heading reading
 * "$00 &NDASH; $3F".
 */

/**
 * Draw one glyph as an inline SVG from its eight ROM bytes.
 *
 * Every pixel is a 1×1 rect in an 8×8 viewBox, so the card prints at whatever
 * resolution the printer has rather than at whatever resolution a PNG was
 * exported at — and the picture is the ROM's own bits, not a screenshot of a
 * font that resembles them.
 */
function glyphSvg(rows) {
  const pixels = []
  rows.forEach((byte, y) => {
    for (let x = 0; x < 8; x++) {
      if (byte & (0x80 >> x)) pixels.push(`<rect x="${x}" y="${y}" width="1" height="1"/>`)
    }
  })
  return `<svg class="glyph" viewBox="0 0 8 8" role="img">${pixels.join('')}</svg>`
}

function characterMap() {
  const charset = facts('charset.json')
  const version = charset.$meta.biosVersion

  // Sixteen rows of sixteen, addressed the way a hex dump is: row = high
  // nibble, column = low nibble.
  const grid = (from, to) => {
    const header =
      '  <thead><tr><th class="th-hex"></th>' +
      Array.from({ length: 16 }, (_, i) => `<th class="th-hex">${i.toString(16).toUpperCase()}</th>`).join('') +
      '</tr></thead>'
    const body = []
    for (let hi = from; hi < to; hi++) {
      const cells = []
      for (let lo = 0; lo < 16; lo++) {
        const ch = charset.chars[hi * 16 + lo]
        cells.push(`<td class="td-glyph" title="${esc(ch.hex)} ${esc(ch.name)}">${glyphSvg(ch.rows)}</td>`)
      }
      body.push(`    <tr><td class="td-hex">${hi.toString(16).toUpperCase()}<em>x</em></td>${cells.join('')}</tr>`)
    }
    return ['<table class="charset-grid">', header, '  <tbody>', body.join('\n'), '  </tbody>', '</table>'].join('\n')
  }

  const names = (from, to) =>
    table([{ label: 'Code', width: '11%' }, { label: '', width: '7%' }, { label: 'Name' }],
      charset.chars.slice(from, to).map((ch) => [
        addr(esc(ch.hex)),
        { cls: 'td-glyph-inline', html: glyphSvg(ch.rows) },
        desc(esc(ch.name))
      ]))

  return card({
    file: 'character-map.html',
    title: '6502 Character Set',
    side: SIDE(`CP437 at ${charset.address} &middot; BIOS v${version}`),
    subtitle: '6502 CHARACTER SET',
    pages: [
      {
        heading: 'Character Set',
        cols: 1,
        sections: [
          section('All 256 characters',
            note(null,
              `The machine's character set is IBM Code Page 437, ${charset.cell}, living in ROM at ` +
              `<code>${esc(charset.address)}</code>. <code>InitVideo</code> copies it into the video ` +
              'card at power-on. Row is the high hex digit, column the low one &mdash; ' +
              `so <code>A</code> is row <code>4</code>, column <code>1</code>: <code>$41</code>.`),
            grid(0, 16)),
          section('What you can PRINT',
            note(null,
              `<code>PRINT</code> reaches <code>${esc(charset.printable.viaChrout)}</code> and four ` +
              'control codes &mdash; carriage return, line feed, backspace and bell. ' +
              '<strong>Everything else it throws away</strong>, including every box-drawing and ' +
              `shading glyph above <code>$7E</code>. Those need <code>${esc(charset.printable.rawRoutine)}</code>, ` +
              'which is an assembly-level call.'))
        ]
      },
      // Three columns, not two. A name row is a hex code, a glyph and two or
      // three words, so at half-page width most of the line was blank — and
      // 128 rows to a page overran the two columns by a fifth, which the page
      // box then clipped off the right edge. Narrower columns fit the content
      // they hold and give the rows somewhere to go.
      {
        heading: 'Character Set',
        cols: 3,
        sections: [
          flowSection('$00 – $3F', names(0x00, 0x40)),
          flowSection('$40 – $7F', names(0x40, 0x80))
        ]
      },
      {
        heading: 'Character Set',
        cols: 3,
        sections: [
          flowSection('$80 – $BF', names(0x80, 0xc0)),
          flowSection('$C0 – $FF', names(0xc0, 0x100))
        ]
      }
    ]
  })
}

