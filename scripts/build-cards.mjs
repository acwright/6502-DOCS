/**
 * Syntax and one-line summary come from `basic-examples.json`, not from
 * `basic-keywords.json`.
 *
 * The generated keywords file carries the BIOS README's text, and Phase 4
 * found six places where that text is wrong — a `NEXT var, var` form the ROM
 * rejects, seven syntax lines pasted from the neighboring entry (ACCURACY.md
 * A21–A26). The examples file is the hand-authored, machine-run correction,
 * and it is what the chapters print. A card that disagreed with the chapter it
 * condenses would be worse than no card.
 */
function basicReference() {
  const keywords = facts('basic-keywords.json')
  const examples = facts('basic-examples.json').keywords
  const errors = facts('errors.json')
  const version = keywords.$meta.biosVersion

  const entry = (name) => {
    const k = keywords.keywords.find((w) => w.name === name)
    const e = examples[name]
    return {
      name,
      kind: k?.kind ?? 'statement',
      token: k?.token,
      syntax: e?.syntax ?? k?.forms?.[0]?.syntax ?? name,
      summary: e?.summary ?? k?.forms?.[0]?.description ?? ''
    }
  }

  const rows = (list) =>
    table(
      [{ label: 'Keyword', width: '22%' }, { label: 'Syntax', width: '38%' }, { label: 'What it does' }],
      list.map((k) => [cmd(esc(k.name)), syn(esc(k.syntax)), desc(rich(k.summary))])
    )

  /**
   * One keyword group as a section. They run on across a column break rather
   * than jumping whole to the next column: on a two-page card the stranded
   * column tails are what the third page was mostly made of.
   */
  const kwSection = (title, list) => flowSection(title, rows(list))

  // Grouped by the job, not by the token table's order. Whatever the groups
  // miss falls into "Everything else", so a keyword added to the ROM appears
  // on the card the moment the fact base is re-extracted, rather than silently
  // vanishing off it.
  const GROUPS = {
    control: ['LET', 'PRINT', 'INPUT', 'GOTO', 'GOSUB', 'RETURN', 'ON', 'IF', 'THEN', 'ELSE',
      'FOR', 'TO', 'STEP', 'NEXT', 'DEF', 'FN', 'END', 'STOP', 'CONT', 'REM'],
    program: ['RUN', 'LIST', 'NEW', 'CLR', 'DIM', 'DATA', 'READ', 'RESTORE'],
    screen: ['CLS', 'LOCATE', 'COLOR', 'SOUND', 'VOL', 'INKEY', 'JOY', 'WAIT', 'PAUSE'],
    files: ['LOAD', 'SAVE', 'DIR', 'DEL', 'DISK', 'FORMAT', 'BLOAD', 'BSAVE'],
    clock: ['TIME', 'DATE', 'SETTIME', 'SETDATE', 'NVRAM'],
    machine: ['PEEK', 'POKE', 'SYS', 'BANK', 'MEM', 'FRE', 'BRK']
  }

  const known = new Set(Object.values(GROUPS).flat())
  for (const name of known) {
    if (!keywords.keywords.some((k) => k.name === name)) {
      throw new Error(`basic-reference: grouped "${name}" is not in the token table any more`)
    }
  }

  const group = (key) => GROUPS[key].map(entry)
  const rest = keywords.keywords.filter((k) => !known.has(k.name)).map((k) => entry(k.name))
  const control = group('control')
  const program = group('program')
  const screen = group('screen')
  const files = group('files')
  const clock = group('clock')
  const machine = group('machine')

  const precedence = table(
    [{ label: 'Rank', width: '14%' }, { label: 'Level', width: '38%' }, { label: 'Operators' }],
    keywords.operatorPrecedence.map((p) => [
      cmd(String(p.rank)),
      desc(esc(p.level)),
      syn(p.operators.map((o) => `<code>${esc(o)}</code>`).join(' '))
    ])
  )

  const errorRows = table(
    [{ label: 'The machine prints', width: '46%' }, { label: 'Because' }],
    errors.basic.errors.map((e) => {
      const cause = ERROR_CAUSE[e.text]
      if (!cause) throw new Error(`basic-reference: no cause written for "${e.printed}"`)
      return [cmd(esc(e.printed)), desc(esc(cause))]
    })
  )

  return card({
    file: 'basic-reference.html',
    title: '6502 BASIC V2.0 — Reference',
    side: SIDE(`BASIC V2.0 &middot; BIOS v${version}`),
    subtitle: `6502 BASIC — QUICK REFERENCE`,
    // Two pages, not three. The keyword tables carry the card, so this is the
    // one sheet that sets its rows tighter than the house default — 1.15 line
    // and half a point of cell padding, which is about 13% off every row and
    // the difference between 1.98 pages of content and 1.82. Nothing is cut.
    style: '--w-cmd: 22%; --w-syn: 38%; --lh-table: 1.15; --pad-td: 0.5px 3.5px',
    pages: [
      {
        heading: 'BASIC Reference',
        sections: [
          section('The shape of a program',
            note('Two modes.',
              'Type a line with a number in front and it is <em>stored</em>; type one without and it ' +
              'runs there and then. <code>RUN</code> runs what is stored, <code>LIST</code> shows it, ' +
              '<code>NEW</code> throws it away. The prompt is <code>OK</code>.'),
            note('Names.',
              'Any length, letters and digits — but only the <strong>first two characters</strong> ' +
              'count, so <code>COUNT</code> and <code>COURSE</code> are the same variable. A name ' +
              'containing a keyword will not parse: <code>SCORE</code> has <code>OR</code> in it.'),
            note('Numbers.',
              'Five-byte floats, about ±1.7&nbsp;×&nbsp;10<sup>38</sup>, nine significant digits. ' +
              'A positive number prints with a leading space where the minus sign would go.')),
          kwSection('Control and flow', control),
          kwSection('The program itself', program),
          kwSection('Screen, sound and sticks', screen),
          kwSection('Files on the card', files),
          kwSection('Clock and lasting memory', clock)
        ]
      },
      {
        heading: 'BASIC Reference',
        sections: [
          kwSection('Reaching the machine', machine),
          kwSection('Functions', rest),
          section('Operator precedence', precedence,
            note('Truth is −1.',
              'A comparison gives <code>-1</code> for true and <code>0</code> for false, and ' +
              '<code>AND</code>, <code>OR</code> and <code>NOT</code> work <em>bitwise</em> on the ' +
              'integer part — which is exactly why the joystick test is ' +
              '<code>IF (JOY(1) AND 16) = 0</code>.')),
          section('Three things that catch everyone',
            note('The loop body always runs once.',
              '<code>FOR</code> tests its limit at the <code>NEXT</code>, so ' +
              '<code>FOR N = 1 TO 0</code> still runs the body one time.'),
            note('One NEXT per loop.',
              '<code>NEXT J, I</code> is not accepted, whatever else you may have read — it fails ' +
              'mid-loop with <code>?NEXT WITHOUT FOR ERROR</code>. Close each loop with its own ' +
              '<code>NEXT</code>.'),
            note('The joystick reads backwards.',
              'A direction being <em>held</em> reads <code>0</code>, not 1. An untouched stick is ' +
              '<code>255</code>.')),
          flowSection('Every error message', errorRows),
          section('Getting out of trouble',
            table([{ label: 'Key', width: '30%' }, { label: 'Does' }], [
              [cmd('Esc'), desc('Stops a running program. <strong>This is the one to remember.</strong>')],
              [cmd('Ctrl + C'), desc('The same thing, for people used to typing it')],
              [cmd('CONT'), desc('Carries on from where <code>STOP</code> or Esc left off')],
              [cmd('Reset button'), desc('Warm start — your program and variables survive')]
            ]))
        ]
      }
    ]
  })
}

